const {chromium}=require('playwright');
const {pathToFileURL}=require('node:url');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.PID_BROWSER_CHANNEL ? {channel:process.env.PID_BROWSER_CHANNEL} : {})});
  const page=await browser.newPage({viewport:{width:1560,height:1120},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const checks=[];
  await page.goto(pathToFileURL(path.join(__dirname,'pid-lab.html')).href);
  await page.waitForFunction(()=>window.__pidLab?.revision()>0);
  await page.locator('#language-select').selectOption('ja');
  assert.equal(await page.locator('svg.chart-svg').count(),3);
  assert.equal(await page.locator('input[type=range]').count(),12);
  assert.equal(await page.locator('#app-error').isVisible(),false);
  checks.push('Offline bundled file loads all controls and three charts');
  async function slide(id,v){const old=await page.evaluate(()=>window.__pidLab.revision());await page.locator('#'+id).fill(String(v));await page.waitForFunction(n=>window.__pidLab.revision()>n,old);}
  await page.locator('#next-step').click();
  assert.match(await page.locator('#calculation').innerText(),/計算 #2/);
  assert.match(await page.locator('#calculation').innerText(),/I = 前回I \+ 採用した増加 = 1.0000 \+ 1.0000 = 2.0000/);
  await page.locator('#form').selectOption('incremental');
  assert.match(await page.locator('#calculation').innerText(),/81.0000 \+ \(0.0000\) \+ \(1.0000\) \+ \(0.0000\) = 82.0000/);
  checks.push('First and second controller calculations retain integral and incremental raw output');
  await page.locator('#save-reference').click();
  await slide('Kp',3);
  assert.equal(await page.locator('[data-series=ref-temperature]').count(),1);
  assert.equal(await page.evaluate(()=>window.__pidLab.reference().result.config.Kp),8);
  assert.equal(await page.evaluate(()=>window.__pidLab.current().config.Kp),3);
  checks.push('Changing slider recomputes result while retaining separate reference');
  await page.locator('#preset').selectOption('saturation');
  await slide('target',60);
  assert.match(await page.locator('#comparison-status').innerText(),/維持できません/);
  assert.ok(await page.evaluate(()=>window.__pidLab.current().stats.integralHeldTime>0));
  const initialI=await page.evaluate(()=>window.__pidLab.current().records.at(-1).I);
  await page.locator('#antiWindup').uncheck();
  await page.waitForFunction(()=>!window.__pidLab.current().config.antiWindup);
  assert.ok(await page.evaluate(i=>window.__pidLab.current().records.at(-1).I>i+100,initialI));
  checks.push('Output saturation and antiwindup changes are visible and numerically active');
  await page.locator('#mode').selectOption('P');
  assert.equal(await page.locator('#Ti').isDisabled(),true);assert.equal(await page.locator('#Td').isDisabled(),true);
  await page.locator('#mode').selectOption('PI');assert.equal(await page.locator('#Ti').isDisabled(),false);
  await page.locator('#preset').selectOption('fast');await page.locator('#clear-reference').click();
  await page.locator('#form').selectOption('position');
  await slide('Ts',.7);await slide('deadTime',10.5);
  await page.locator('#time-cursor').fill('17.3');
  const state=await page.evaluate(()=>({text:document.getElementById('temperature-value').textContent,result:window.__pidLab.current().samples.filter(s=>s.t<=17.3).at(-1)}));
  assert.ok(parseFloat(state.text)>20);checks.push('Fractional control period and dead time render correctly');
  await page.locator('#play').click();await page.waitForTimeout(300);assert.ok(parseFloat(await page.locator('#time-label').innerText())>17.3);await page.locator('#play').click();
  await page.locator('#preset').selectOption('fast');
  await page.locator('#time-cursor').fill('35');
  await page.screenshot({path:path.join(__dirname,'desktop.png'),fullPage:true});
  const boxes=[];
  for(const width of [1280,1024,736,360,320]){
    await page.setViewportSize({width,height:1000});await page.waitForTimeout(180);
    const info=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth,
      bad:[...document.querySelectorAll('svg text')].map(e=>({s:e.closest('svg').getBoundingClientRect(),r:e.getBoundingClientRect(),t:e.textContent})).filter(x=>x.r.left<x.s.left-1||x.r.right>x.s.right+1).map(x=>x.t)}));
    assert.ok(info.scroll<=info.client+1,JSON.stringify({width,...info}));assert.deepEqual(info.bad,[]);boxes.push({width,...info});
  }
  await page.screenshot({path:path.join(__dirname,'mobile.png'),fullPage:true});
  await page.locator('#temperature-chart').screenshot({path:path.join(__dirname,'mobile-chart.png')});
  checks.push('320/360/736/1024/1280px layouts have no horizontal overflow or clipped chart labels');
  await page.setViewportSize({width:1560,height:1120});
  await page.locator('#temperature-legend button').first().click();assert.equal(await page.locator('[data-series=temperature]').count(),0);
  await page.locator('#temperature-legend button').first().click();assert.equal(await page.locator('[data-series=temperature]').count(),1);
  const box=await page.locator('#temperature-chart [data-chart-hit]').boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  assert.equal(await page.locator('#chart-tooltip').isVisible(),true);checks.push('Legend toggles and cross-series tooltip work');
  await page.locator('#horizon').selectOption('1800');await slide('Ts',.1);
  assert.equal(await page.evaluate(()=>window.__pidLab.current().records.length),18001);
  const computeMs=await page.evaluate(()=>window.__pidLab.computeMs);assert.ok(computeMs<3000);
  checks.push('Longest supported run / fastest sample remains interactive');
  assert.deepEqual(errors,[]);
  const result={checks,boxes,computeMs,errors};fs.writeFileSync(path.join(__dirname,'ui-verification.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
